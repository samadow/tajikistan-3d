export type StringKey = keyof (typeof strings)['en']
export type Translate = (key: StringKey) => string

export function translate(lang: Lang, key: StringKey): string {
  return strings[lang][key]
}

export function useT(): Translate {
  const lang = useAppStore((s) => s.lang)
  return (key: StringKey) => strings[lang][key]
}

/** Years: negative = BCE. Approximate dates get a prefix (≈ / c.). */
export function formatYear(year: number, t: Translate, approximate = false): string {
  const prefix = approximate ? `${t('approx')} ` : ''
  return year < 0 ? `${prefix}${Math.abs(year)} ${t('bce')}` : `${prefix}${year}`
}

export function formatRange(start: number, end: number | null, t: Translate, approximate = false): string {
  if (end === null) return formatYear(start, t, approximate)
  if (start < 0 && end < 0) return `${approximate ? `${t('approx')} ` : ''}${Math.abs(start)}–${Math.abs(end)} ${t('bce')}`
  return `${formatYear(start, t, approximate)} – ${formatYear(end, t)}`
}

/**
 * Number formatting per language. Tajik uses the same digit grouping as
 * Russian (thin space); not every browser ships Tajik locale data, so ru-RU
 * rules are used for both.
 */
export function formatNumber(value: number, lang: Lang, digits = 0): string {
  return new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'ru-RU', { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(value)
}

export function formatCoordinates(lat: number, lon: number, lang: Lang, t: Translate): string {
  return `${formatNumber(lat, lang, 3)}° ${t('north')}, ${formatNumber(lon, lang, 3)}° ${t('east')}`
}

